/**
 * The app's icon set. One place decides how every icon looks: Phosphor, drawn light and square-ended so they sit
 * with the serif headings. Screens import icons from here by a plain name and size them with className, so nothing
 * else in the app knows which library draws them.
 */
export type AppIconProps = Omit<IconProps, 'weight' | 'ref'> & { strokeWidth?: number | string; absoluteStrokeWidth?: boolean };
export type AppIcon = React.ForwardRefExoticComponent<AppIconProps & React.RefAttributes<SVGSVGElement>>;

type PhosphorLike = React.ForwardRefExoticComponent<IconProps>;

function make(Base: PhosphorLike, name: string): AppIcon {
  const Icon = React.forwardRef<SVGSVGElement, AppIconProps>(({ strokeWidth: _s, absoluteStrokeWidth: _a, ...props }, ref) => (
    <Base ref={ref} weight="light" aria-hidden={props['aria-label'] ? undefined : true} {...props} />
  ));
  Icon.displayName = name;
  return Icon;
}

